-- 009_sync_missing_schema.sql
--
-- A number of tables and columns were added directly to the local database
-- over the course of development, outside any tracked migration file. This
-- is why a fresh deployment (Supabase) came up missing 9 whole tables and
-- several columns on existing ones. This migration brings any database up
-- to match the real local schema, whether it's missing everything here or
-- just a piece of it. Every statement uses IF NOT EXISTS, so it's safe to
-- run on a database that already has some of this.
--
-- Safe to run more than once.

BEGIN;

-- ── Missing columns on existing tables ──────────────────────────────────

ALTER TABLE users  ADD COLUMN IF NOT EXISTS is_approved boolean DEFAULT true;
ALTER TABLE users  ADD COLUMN IF NOT EXISTS plot_id integer;
ALTER TABLE users  ADD COLUMN IF NOT EXISTS last_notices_read_at timestamp without time zone;

ALTER TABLE plots  ADD COLUMN IF NOT EXISTS agent_id integer;

ALTER TABLE houses ADD COLUMN IF NOT EXISTS is_approved boolean DEFAULT true;
ALTER TABLE houses ADD COLUMN IF NOT EXISTS rejection_reason text;
ALTER TABLE houses ADD COLUMN IF NOT EXISTS status_changed_at timestamp without time zone DEFAULT now();
ALTER TABLE houses ADD COLUMN IF NOT EXISTS listed boolean DEFAULT true;

-- Foreign keys for the columns above — wrapped so re-running this doesn't
-- error if the constraint already exists.
DO $$ BEGIN
  ALTER TABLE users ADD CONSTRAINT users_plot_id_fkey
    FOREIGN KEY (plot_id) REFERENCES plots(id) ON DELETE SET NULL;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  ALTER TABLE plots ADD CONSTRAINT plots_agent_id_fkey
    FOREIGN KEY (agent_id) REFERENCES users(id) ON DELETE SET NULL;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- ── Tables that didn't exist on this database at all ────────────────────

CREATE TABLE IF NOT EXISTS caretaker_plots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caretaker_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  plot_id integer NOT NULL REFERENCES plots(id) ON DELETE CASCADE,
  assigned_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS notices (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title character varying(255) NOT NULL,
  body text NOT NULL,
  priority character varying(10) NOT NULL DEFAULT 'info'
    CHECK (priority IN ('info', 'warning', 'urgent')),
  target_type character varying(20) NOT NULL DEFAULT 'all'
    CHECK (target_type IN ('all', 'staff', 'property', 'unit', 'tenant')),
  target_id integer,
  expires_at timestamp with time zone,
  created_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS notice_reads (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notice_id integer NOT NULL REFERENCES notices(id) ON DELETE CASCADE,
  tenant_id integer NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  read_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS conversations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notice_id integer REFERENCES notices(id) ON DELETE SET NULL,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS conversation_participants (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id integer NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  participant_id integer NOT NULL,
  participant_type character varying(10) NOT NULL CHECK (participant_type IN ('user', 'tenant')),
  last_read_at timestamp with time zone
);

CREATE TABLE IF NOT EXISTS messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id integer NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  sender_id integer NOT NULL,
  sender_type character varying(10) NOT NULL CHECK (sender_type IN ('user', 'tenant')),
  body text NOT NULL,
  created_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tenant_otps (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id integer NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  otp_hash character varying(255) NOT NULL,
  expires_at timestamp with time zone NOT NULL,
  used boolean DEFAULT false,
  created_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token character varying(255) NOT NULL,
  expires_at timestamp with time zone NOT NULL,
  used boolean DEFAULT false,
  created_at timestamp with time zone DEFAULT now()
);

CREATE TABLE IF NOT EXISTS plot_media (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  house_id integer NOT NULL REFERENCES houses(id) ON DELETE CASCADE,
  filename character varying(500) NOT NULL,
  media_type character varying(10) NOT NULL CHECK (media_type IN ('photo', 'video')),
  sort_order integer DEFAULT 0,
  created_at timestamp with time zone DEFAULT now()
);

-- ── Indexes (IF NOT EXISTS makes these safe to re-run too) ──────────────

CREATE INDEX IF NOT EXISTS idx_users_agent_id      ON users (agent_id);
CREATE INDEX IF NOT EXISTS idx_houses_published    ON houses (is_published, status) WHERE is_published = true;
CREATE INDEX IF NOT EXISTS idx_notices_author       ON notices (author_id);
CREATE INDEX IF NOT EXISTS idx_conv_participants    ON conversation_participants (conversation_id);
CREATE INDEX IF NOT EXISTS idx_messages_conv        ON messages (conversation_id);
CREATE INDEX IF NOT EXISTS idx_deposit_tx_tenant     ON deposit_transactions (tenant_id);
CREATE INDEX IF NOT EXISTS idx_tenant_otps_tenant    ON tenant_otps (tenant_id);
CREATE INDEX IF NOT EXISTS idx_plot_media_house      ON plot_media (house_id);

COMMIT;
